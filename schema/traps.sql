CREATE TABLE `traps` (
  `id` int NOT NULL AUTO_INCREMENT,
  `zone` varchar(16) NOT NULL DEFAULT '',
  `version` smallint unsigned NOT NULL DEFAULT '0',
  `x` int NOT NULL DEFAULT '0',
  `y` int NOT NULL DEFAULT '0',
  `z` int NOT NULL DEFAULT '0',
  `chance` tinyint NOT NULL DEFAULT '0',
  `maxzdiff` float NOT NULL DEFAULT '0',
  `radius` float NOT NULL DEFAULT '0',
  `effect` int NOT NULL DEFAULT '0',
  `effectvalue` int NOT NULL DEFAULT '0',
  `effectvalue2` int NOT NULL DEFAULT '0',
  `message` varchar(200) NOT NULL DEFAULT '',
  `skill` int NOT NULL DEFAULT '0',
  `level` mediumint unsigned NOT NULL DEFAULT '1',
  `respawn_time` int unsigned NOT NULL DEFAULT '60',
  `respawn_var` int unsigned NOT NULL DEFAULT '0',
  `triggered_number` tinyint NOT NULL DEFAULT '0',
  `group` tinyint NOT NULL DEFAULT '0',
  `despawn_when_triggered` tinyint NOT NULL DEFAULT '0',
  `undetectable` tinyint NOT NULL DEFAULT '0',
  `min_expansion` tinyint NOT NULL DEFAULT '-1',
  `max_expansion` tinyint NOT NULL DEFAULT '-1',
  `content_flags` varchar(100) DEFAULT NULL,
  `content_flags_disabled` varchar(100) DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `zone` (`zone`)
) ENGINE=InnoDB DEFAULT CHARSET=latin1;
