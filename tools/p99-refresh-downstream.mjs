import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {findProposals,mergeProposals} from './p99-merge-proposals.mjs';
const root=path.resolve(process.argv[2]??'.');
const read=async p=>JSON.parse(await fs.readFile(path.join(root,p),'utf8'));
const manifest=await read('manifest.json');
const keys=Object.fromEntries(Object.entries(manifest.tables).map(([k,v])=>[k,v.primaryKey]));
const proposal=mergeProposals((await findProposals(root)).map(p=>p.value),'downstream-reconciliation',keys);
const generated=[];
for(const source of proposal.sources.filter(s=>s.target.endsWith('.lua'))) {
 const content=await fs.readFile(path.join(root,source.proposedFile),'utf8');
 const instructions=content.split('\n').filter(line=>/^--.*(?:Generated by|generated from|edit .*\.json)/i.test(line));
 if(instructions.length)generated.push({proposedFile:source.proposedFile,sha256:crypto.createHash('sha256').update(content).digest('hex'),generatorInstructions:instructions,
  requiredAction:'Mirror the reviewed behavior in the authoritative game-repository generator/configuration before regeneration. This content-only audit did not modify that separate repository.',status:'downstream synchronization required'});
}
await fs.writeFile(path.join(root,'changes/p99-audit/generator-sync.json'),JSON.stringify({scope:'Generated-source edits within this proposal package only. Not permission to modify the separate game repository.',records:generated},null,2)+'\n');
const newRows=proposal.rows.filter(r=>r.table==='quests'&&r.before===null&&r.after).map(r=>r.after);
const normalize=name=>name.replaceAll('`','-').replaceAll(' ','_');
const wantedNames=new Set(newRows.map(r=>normalize(r.name)));
const loadRows=async(table,predicate)=>{
 const rows=[];for(const file of manifest.tables[table].shards) {
  for(const line of (await fs.readFile(path.join(root,file),'utf8')).split('\n').filter(Boolean)) {
   const row=JSON.parse(line);if(predicate(row))rows.push(row);
  }
 }return rows;
};
const npcs=await loadRows('npc_types',n=>wantedNames.has(normalize(n.name)));
const npcIds=new Set(npcs.map(n=>n.id));
const entries=await loadRows('spawnentry',e=>npcIds.has(e.npcID));
const groups=new Set(entries.map(e=>e.spawngroupID));
const spawns=await loadRows('spawn2',s=>groups.has(s.spawngroupID));
const policy=await read('reference/server/internal/contentscope/npc_exclusions.json');
const exclusions=[...(policy.npcs??[]),...(policy.additional_npcs??[]),...(policy.inactive_npcs??[])];
const zones=new Set(await read('changes/p99-audit/p99_zones.json'));
const records=newRows.map(row=>({key:`${row.zone}/${row.name}`,questId:row.id,p99Zone:zones.has(row.zone),
 npcCandidates:npcs.filter(n=>normalize(n.name)===normalize(row.name)).map(n=>{
  const spawnEntries=entries.filter(e=>e.npcID===n.id),groups=new Set(spawnEntries.map(e=>e.spawngroupID));
  return {npcId:n.id,name:n.name,exclude:n.exclude,loottableId:n.loottable_id,spawnEntries,
   explicitNpcPolicy:exclusions.filter(e=>e.id===n.id),
   inZoneSpawnRows:spawns.filter(s=>s.zone===row.zone&&groups.has(s.spawngroupID))};
 })}));
await fs.writeFile(path.join(root,'changes/p99-audit/new-actor-static-dependencies.json'),JSON.stringify({
 limits:'Static exported identity/spawn graph only; exclude flag alone is not runtime policy. Exact names use only the documented backtick-to-dash and space normalization. Spawn filtering, inventory, event lifecycle and complete acquisition are not executed. Alternate-zone aliases do not activate those zones.',records},null,2)+'\n');
console.log(JSON.stringify({generatedSources:generated.length,newActors:records.length,withoutNpcCandidate:records.filter(r=>!r.npcCandidates.length).map(r=>r.key)}));
