import fs from 'node:fs/promises';
import path from 'node:path';
import { quote, hash } from './dataset.mjs';
import { relations } from './relations.mjs';

export function sqlValue(value) {
  if (value === null) return 'NULL';
  if (typeof value === 'number' && Number.isFinite(value)) return String(value);
  if (typeof value === 'string') return `CONVERT(X'${Buffer.from(value).toString('hex')}' USING utf8mb4)`;
  if (value && Object.keys(value).length===1 && typeof value.$binary==='string') return `X'${Buffer.from(value.$binary,'base64').toString('hex')}'`;
  throw new Error('Unsupported SQL value');
}

export function schemaColumns(schema) {
  const columns=[];
  for (const line of schema.split('\n')) {
    const match=line.match(/^  `([^`]+)` (.+)/);
    if (!match) continue;
    const definition=match[2];
    let depth=0, quoted=false, end=definition.length;
    for (let i=0;i<definition.length;i++) {
      const c=definition[i];
      if (c==='\\' && quoted) { i++; continue; }
      if(c==="'") { if(quoted&&definition[i+1]==="'") { i++;continue; } quoted=!quoted; }
      if(quoted) continue;
      if(c==='(') depth++;
      if(c===')') depth--;
      if((c===' '||c===',')&&depth===0) { end=i;break; }
    }
    let type=definition.slice(0,end);
    const modifiers=definition.slice(end).match(/^(?: unsigned)?(?: zerofill)?/)[0];
    type+=modifiers;
    columns.push({name:match[1],type,nullable:!definition.includes('NOT NULL')});
  }
  if (!columns.length) throw new Error('No columns found in schema');
  return columns;
}

function equal(column,value,types) {
  const type=types.find(c=>c.name===column)?.type;
  if (!type) throw new Error(`Unknown column ${column}`);
  const numeric=/^(tinyint|smallint|mediumint|int|bigint|float|double|decimal|bit|year)\b/.test(type);
  let literal=numeric&&typeof value==='string'&&/^-?\d+(?:\.\d+)?$/.test(value)?value:sqlValue(value);
  // MySQL stores FLOAT at lower precision than its numeric literal parser. Cast
  // the expected value to the storage type before exact comparison (0.3 matters).
  if(/^float\b/.test(type)&&value!==null) literal=`CAST(${literal} AS FLOAT)`;
  return numeric ? `${quote(column)} <=> ${literal}` : `BINARY ${quote(column)} <=> BINARY ${literal}`;
}

// Plain SQL plugs into the existing migration runner (mysql batch mode, without
// --force). A failed CHECK aborts that client; closing it rolls back the InnoDB
// transaction. No persistent DDL/procedure or separate deployment system needed.
export async function generateMigration(root, manifest, proposal, revision) {
  const guard=`content_guard_${hash(proposal.id).slice(0,12)}`;
  const out=[`-- Content proposal ${proposal.id}; reviewed revision ${revision}`,
    '-- Generated by scripts/content. Do not run with mysql --force.',
    `CREATE TEMPORARY TABLE ${quote(guard)} (reason varchar(255) NOT NULL, ok tinyint NOT NULL, CONSTRAINT content_expected_before CHECK (ok=1)) ENGINE=InnoDB;`,
    'SET TRANSACTION ISOLATION LEVEL SERIALIZABLE;', 'START TRANSACTION;'];
  const assert=(label,condition)=>out.push(`INSERT INTO ${quote(guard)} (reason,ok) SELECT ${sqlValue(label)}, IF((${condition}),1,0);`);
  const types=new Map();
  for(const name of new Set(proposal.rows.map(c=>c.table))) {
    const columns=schemaColumns(await fs.readFile(path.join(root,`schema/${name}.sql`),'utf8'));
    types.set(name,columns);
    assert(`InnoDB ${name}`,`EXISTS(SELECT 1 FROM information_schema.tables WHERE table_schema=DATABASE() AND table_name=${sqlValue(name)} AND engine='InnoDB')`);
    assert(`schema column count ${name}`,`(SELECT COUNT(*) FROM information_schema.columns WHERE table_schema=DATABASE() AND table_name=${sqlValue(name)})=${columns.length}`);
    for(const column of columns) assert(`schema ${name}.${column.name}`,`EXISTS(SELECT 1 FROM information_schema.columns WHERE table_schema=DATABASE() AND table_name=${sqlValue(name)} AND BINARY column_name=${sqlValue(column.name)} AND BINARY column_type=${sqlValue(column.type)} AND is_nullable='${column.nullable?'YES':'NO'}')`);
    const primary=manifest.tables[name].primaryKey;
    assert(`primary key ${name}`,`(SELECT COUNT(*) FROM information_schema.statistics WHERE table_schema=DATABASE() AND table_name=${sqlValue(name)} AND index_name='PRIMARY')=${primary.length}`);
    for(const [index,key] of primary.entries()) assert(`primary key ${name}.${key}`,`EXISTS(SELECT 1 FROM information_schema.statistics WHERE table_schema=DATABASE() AND table_name=${sqlValue(name)} AND index_name='PRIMARY' AND seq_in_index=${index+1} AND BINARY column_name=${sqlValue(key)})`);
  }
  for(const change of proposal.rows) {
    const table=manifest.tables[change.table], columns=types.get(change.table);
    const key=table.primaryKey.map((k,i)=>equal(k,change.key[i],columns)).join(' AND ');
    const predicate=row=>row===null?`NOT EXISTS(SELECT 1 FROM ${quote(change.table)} WHERE ${key})`:
      `EXISTS(SELECT 1 FROM ${quote(change.table)} WHERE ${table.columns.map(c=>equal(c,row[c],columns)).join(' AND ')})`;
    out.push(`SELECT ${table.primaryKey.map(quote).join(',')} FROM ${quote(change.table)} WHERE ${key} FOR UPDATE;`);
    assert(`preimage ${change.table} ${JSON.stringify(change.key).slice(0,150)}`,`${predicate(change.before)} OR ${predicate(change.after)}`);
    const before=change.before&&table.columns.map(c=>equal(c,change.before[c],columns)).join(' AND ');
    if(change.after===null) out.push(`DELETE FROM ${quote(change.table)} WHERE ${before};`);
    else if(change.before===null) out.push(`INSERT INTO ${quote(change.table)} (${table.columns.map(quote).join(',')}) SELECT ${table.columns.map(c=>sqlValue(change.after[c])).join(',')} WHERE NOT EXISTS(SELECT 1 FROM ${quote(change.table)} WHERE ${key});`);
    else out.push(`UPDATE ${quote(change.table)} SET ${table.columns.filter(c=>!table.primaryKey.includes(c)).map(c=>`${quote(c)}=${sqlValue(change.after[c])}`).join(',')} WHERE ${before};`);
    assert(`postimage ${change.table} ${JSON.stringify(change.key).slice(0,150)}`,predicate(change.after));
  }
  for(const change of proposal.rows) for(const [source,field,target,key] of relations) {
    if(change.table===source&&change.after&&Number(change.after[field])>0&&(!change.before||change.before[field]!==change.after[field])) assert(`reference ${source}.${field}`,`EXISTS(SELECT 1 FROM ${quote(target)} WHERE ${quote(key)}=${sqlValue(change.after[field])})`);
    if(change.table===target&&change.before&&!change.after) assert(`inbound ${target}.${key}`,`EXISTS(SELECT 1 FROM ${quote(target)} WHERE ${quote(key)}=${sqlValue(change.before[key])}) OR NOT EXISTS(SELECT 1 FROM ${quote(source)} WHERE ${quote(field)}=${sqlValue(change.before[key])})`);
  }
  out.push('COMMIT;',`DROP TEMPORARY TABLE ${quote(guard)};`);
  return out.join('\n')+'\n';
}
